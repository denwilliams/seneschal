import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fixture } from "./fixture.ts";
import { SecretAdmin } from "../config/managed-env.ts";
import { ScopedSecretAdmin, keychainWriter } from "../config/scoped-secrets.ts";
import { HarnessConfigSchema } from "../config/schema.ts";
import { KeychainClient } from "../config/keychain.ts";

test("Admin reports unavailable Keychain without blocking environment writes for host bash", async (t) => {
  const f = fixture();
  const dir = mkdtempSync(join(tmpdir(), "host-bash-env-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const file = join(dir, "managed.json");
  const config = HarnessConfigSchema.parse({ defaults: { tools: ["bash"], sandbox: { mode: "host" } } });
  f.source.admin = { configPath: join(f.dataDir, "config.yaml"), dataDir: f.dataDir };
  f.source.secrets = new SecretAdmin(file, undefined, {});
  f.source.scopedSecrets = new ScopedSecretAdmin([keychainWriter(() => config, f.dataDir)], () => [{ id: "C1" }]);
  await f.server.start(); t.after(() => f.server.stop());
  const url = `http://127.0.0.1:${(f.server.address() as { port: number }).port}/console2/api/v1/secrets`;
  const headers = { host: "console.test", "content-type": "application/json", "x-console-admin": "1" };
  const response = await fetch(url, { headers });
  assert.equal(response.status, 200);
  const snapshot = await response.json() as ReturnType<SecretAdmin["snapshot"]> & { scoped: ReturnType<ScopedSecretAdmin["snapshot"]> };
  assert.equal(snapshot.enabled, true);
  assert.equal(snapshot.scoped.backends[0]!.enabled, false);
  assert.match(snapshot.scoped.backends[0]!.unavailableReason!, /host bash.*Docker or Apple Containers.*\.env/);
  const environment = await fetch(url, { method: "POST", headers, body: JSON.stringify({ operation: "save", name: "EXAMPLE_KEY", value: "environment-sentinel", overwrite: false }) });
  assert.equal(environment.status, 200);
  assert.equal(JSON.parse(readFileSync(file, "utf8")).EXAMPLE_KEY, "environment-sentinel");
  const keychain = await fetch(url, { method: "POST", headers, body: JSON.stringify({ operation: "backend-save", backend: "macos-keychain", scope: { kind: "main-process" }, name: "EXAMPLE_KEY", value: "keychain-sentinel", overwrite: true }) });
  assert.equal(keychain.status, 503);
  assert.doesNotMatch(await (await fetch(url, { headers })).text(), /environment-sentinel|keychain-sentinel/);
});

test("Admin shows accepted host risk without claiming Keychain is unavailable and retains write-only storage", async (t) => {
  const platform = Object.getOwnPropertyDescriptor(process, "platform")!;
  Object.defineProperty(process, "platform", { value: "darwin" });
  t.after(() => Object.defineProperty(process, "platform", platform));
  const f = fixture();
  const config = HarnessConfigSchema.parse({ defaults: { tools: ["bash", "exec"], sandbox: { mode: "host" } }, keychain: { helperPath: "/private/helper", acceptHostExecutionRisk: true, adminWrites: true } });
  f.source.admin = { configPath: join(f.dataDir, "config.yaml"), dataDir: f.dataDir };
  f.source.secrets = new SecretAdmin(join(f.dataDir, "managed.json"), undefined, {});
  f.source.scopedSecrets = new ScopedSecretAdmin([keychainWriter(() => config, f.dataDir)], () => [{ id: "C1" }]);
  const write = t.mock.method(KeychainClient.prototype, "write", () => {});
  await f.server.start(); t.after(() => f.server.stop());
  const url = `http://127.0.0.1:${(f.server.address() as { port: number }).port}/console2/api/v1/secrets`;
  const headers = { host: "console.test", "content-type": "application/json", "x-console-admin": "1" };
  const response = await fetch(url, { headers });
  assert.equal(response.status, 200);
  const snapshot = await response.json() as { scoped: ReturnType<ScopedSecretAdmin["snapshot"]> };
  const backend = snapshot.scoped.backends[0]!;
  assert.equal(backend.enabled, true);
  assert.equal(backend.unavailableReason, undefined);
  assert.match(backend.warning!, /risk accepted.*outside configured channel scopes.*Container channels do not isolate their secrets from the host/);
  const result = await fetch(url, { method: "POST", headers, body: JSON.stringify({ operation: "backend-save", backend: "macos-keychain", scope: { kind: "channel", channel: "C1" }, name: "EXAMPLE_KEY", value: "keychain-sentinel", overwrite: true }) });
  assert.equal(result.status, 200);
  assert.equal(write.mock.callCount(), 1);
  assert.deepEqual(write.mock.calls[0]!.arguments, ["save", { kind: "channel", channel: "C1" }, "EXAMPLE_KEY", "keychain-sentinel"]);
  assert.doesNotMatch(await (await fetch(url, { headers })).text(), /keychain-sentinel/);
  config.keychain!.acceptHostExecutionRisk = false;
  const strict = await (await fetch(url, { headers })).json() as typeof snapshot;
  assert.equal(strict.scoped.backends[0]!.enabled, false);
  assert.equal(strict.scoped.backends[0]!.warning, undefined);
});
