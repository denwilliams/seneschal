import { expect, test } from "@playwright/test";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { ADMIN_CONFIG } from "../mock/admin";
import { rawEditor, rawText } from "./yaml-editor-helper";
test.skip(!process.env.SCREENSHOTS, "Opt-in connector documentation screenshots");
const out = resolve(process.cwd(), "../../docs/screenshots/connector-settings");
for (const theme of ["light", "dark"] as const) test(theme + " connector forms and 390px YAML", async ({ page }) => {
  mkdirSync(out, { recursive: true });
  await page.request.post("__mock", { data: { reset: true } });
  await page.emulateMedia({ colorScheme: theme });
  await page.setViewportSize({ width: 1100, height: 1000 });
  await page.goto("./#/admin");
  await expect.poll(() => rawText(page)).toBe(ADMIN_CONFIG);
  await rawEditor(page).fill(ADMIN_CONFIG + "    description: Shared GitHub tools\n    allowTools: [get_issue, list_pull_requests]\n  local-tools:\n    transport: stdio\n    command: npx\n    args: [-y, '@example/mcp-server']\n    env:\n      API_TOKEN: ${LOCAL_API_TOKEN}\n");
  await page.getByRole("button", { name: "Basic settings", exact: true }).click();
  await expect(page.getByTestId("connection")).toContainText("Connected");
  const section = page.getByRole("region", { name: "Connector management" });
  await page.mouse.move(0, 0);
  await section.screenshot({ path: out + "/" + theme + "-http.png", scale: "css" });
  await page.getByLabel("Connector", { exact: true }).selectOption("local-tools");
  await expect(page.getByLabel("Connector command")).toHaveValue("npx");
  await section.screenshot({ path: out + "/" + theme + "-stdio.png", scale: "css" });
  await page.setViewportSize({ width: 390, height: 1000 });
  await page.getByRole("button", { name: "Connector YAML", exact: true }).click();
  await expect(page.getByLabel("Connector definition YAML")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0);
  await section.screenshot({ path: out + "/" + theme + "-yaml-390.png", scale: "css" });
});
